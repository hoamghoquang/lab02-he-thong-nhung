static char rxLine[64];
static uint32_t rxLen = 0;
static char uartRxLine[64];
static uint32_t uartRxLen = 0;

static void ProcessCommand(char *cmd, uint8_t from_uart)
{
  const char *reply;

  if (strcmp(cmd, "Hello STM") == 0)
  {
    reply = "Do you want to turn on or off light?\r\n";
  }
  else if (strcmp(cmd, "Turn on LED 1") == 0)
  {
    HAL_GPIO_WritePin(GPIOA, GPIO_PIN_6, GPIO_PIN_SET);
    reply = "LED 1 turned on\r\n";
  }
  else if (strcmp(cmd, "Turn off LED 1") == 0)
  {
    HAL_GPIO_WritePin(GPIOA, GPIO_PIN_6, GPIO_PIN_RESET);
    reply = "LED 1 turned off\r\n";
  }
  else if (strcmp(cmd, "Turn on LED 2") == 0)
  {
    HAL_GPIO_WritePin(GPIOA, GPIO_PIN_7, GPIO_PIN_SET);
    reply = "LED 2 turned on\r\n";
  }
  else if (strcmp(cmd, "Turn off LED 2") == 0)
  {
    HAL_GPIO_WritePin(GPIOA, GPIO_PIN_7, GPIO_PIN_RESET);
    reply = "LED 2 turned off\r\n";
  }
  else
  {
    reply = "Unknown command\r\n";
  }

  if (from_uart)
  {
    HAL_UART_Transmit(&huart2, (uint8_t *)reply, (uint16_t)strlen(reply), 100);
  }
  else
  {
    CDC_Transmit_FS((uint8_t *)reply, (uint16_t)strlen(reply));
  }
}

static void UART_ProcessInput(void)
{
  uint8_t c;

  while (HAL_UART_Receive(&huart2, &c, 1, 0) == HAL_OK)
  {
    if (c == '\r' || c == '\n')
    {
      if (uartRxLen > 0)
      {
        uartRxLine[uartRxLen] = '\0';
        ProcessCommand(uartRxLine, 1);
        uartRxLen = 0;
      }
    }
    else if (uartRxLen < sizeof(uartRxLine) - 1)
    {
      uartRxLine[uartRxLen++] = (char)c;
    }
    else
    {
      uartRxLen = 0;
    }
  }
}

void USB_CDC_RxHandler(uint8_t *Buf, uint32_t Len)
{
  for (uint32_t i = 0; i < Len; i++)
  {
    char c = (char)Buf[i];

    if (c == '\r' || c == '\n')
    {
      if (rxLen > 0)
      {
        rxLine[rxLen] = '\0';
        ProcessCommand(rxLine, 0);
        rxLen = 0;
      }
    }
    else if (rxLen < sizeof(rxLine) - 1)
    {
      rxLine[rxLen++] = c;
    }
    else
    {
      rxLen = 0;
    }
  }
}
